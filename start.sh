#!/bin/bash
# Quick Start Script for EDSC Blockchain Platform
# Run this script to compile and start the system

echo ""
echo "??????????????????????????????????????????????????????????????????"
echo "?   EDSC Blockchain Platform - Quick Start Script              ?"
echo "??????????????????????????????????????????????????????????????????"
echo ""

# Step 1: Check if Java is installed
echo "[1/4] Checking Java installation..."
if command -v java &> /dev/null; then
    echo "? Java is installed"
    java -version 2>&1 | head -1
else
    echo "? Java is NOT installed"
    echo "   Please install Java 8 or higher and try again"
    exit 1
fi

echo ""

# Step 2: Compile the code
echo "[2/4] Compiling source code..."

if [ -d "out/production/blockchainProjekt" ]; then
    echo "   Cleaning previous build..."
    rm -rf "out/production/blockchainProjekt"
fi

mkdir -p "out/production/blockchainProjekt"

javac -d out/production/blockchainProjekt src/com/company/*.java
if [ $? -eq 0 ]; then
    echo "? Compilation successful!"
else
    echo "? Compilation failed!"
    echo "   Check the error messages above and try again"
    exit 1
fi

echo ""

# Step 3: Show menu
echo "[3/4] Preparing to launch..."
echo ""
echo "??????????????????????????????????????????????"
echo "?           Launch Options                   ?"
echo "??????????????????????????????????????????????"
echo "?  1. Run Full System (Main.java)           ?"
echo "?  2. Run Unit Tests (EDSCTest.java)        ?"
echo "?  3. Exit                                  ?"
echo "??????????????????????????????????????????????"
echo ""

read -p "Select option (1-3): " choice

echo ""

# Step 4: Execute selected option
echo "[4/4] Launching application..."
echo ""

case $choice in
    1)
        echo "Starting EDSC Full System..."
        echo "????????????????????????????????????????????????"
        echo ""
        java -cp out/production/blockchainProjekt com.company.Main
        ;;
    2)
        echo "Running Unit Tests..."
        echo "????????????????????????????????????????????????"
        echo ""
        java -cp out/production/blockchainProjekt com.company.EDSCTest
        ;;
    3)
        echo "Exiting..."
        exit 0
        ;;
    *)
        echo "? Invalid option. Please select 1, 2, or 3."
        exit 1
        ;;
esac

echo ""
echo "? Program completed successfully!"
