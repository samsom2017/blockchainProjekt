# Quick Start Script for EDSC Blockchain Platform
# Run this script to compile and start the system

Write-Host "??????????????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host "?   EDSC Blockchain Platform - Quick Start Script              ?" -ForegroundColor Cyan
Write-Host "??????????????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host ""

# Step 1: Check if Java is installed
Write-Host "[1/4] Checking Java installation..." -ForegroundColor Yellow
$javaVersion = java -version 2>&1
if ($LASTEXITCODE -eq 0) {
    Write-Host "? Java is installed" -ForegroundColor Green
    Write-Host "      Version: $($javaVersion[0])" -ForegroundColor Green
} else {
    Write-Host "? Java is NOT installed" -ForegroundColor Red
    Write-Host "   Please install Java 8 or higher and try again" -ForegroundColor Red
    exit 1
}

Write-Host ""

# Step 2: Compile the code
Write-Host "[2/4] Compiling source code..." -ForegroundColor Yellow
if (Test-Path "out\production\blockchainProjekt") {
    Write-Host "   Cleaning previous build..." -ForegroundColor Gray
    Remove-Item -Recurse -Force "out\production\blockchainProjekt" -ErrorAction SilentlyContinue
}

New-Item -ItemType Directory -Force -Path "out\production\blockchainProjekt" | Out-Null

javac -d out/production/blockchainProjekt src/com/company/*.java 2>&1 | Tee-Object -Variable compileOutput | Out-Host

if ($LASTEXITCODE -eq 0) {
    Write-Host "? Compilation successful!" -ForegroundColor Green
} else {
    Write-Host "? Compilation failed!" -ForegroundColor Red
    Write-Host "Error output:" -ForegroundColor Red
    Write-Host $compileOutput -ForegroundColor Red
    exit 1
}

Write-Host ""

# Step 3: Show menu
Write-Host "[3/4] Preparing to launch..." -ForegroundColor Yellow
Write-Host ""
Write-Host "??????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host "?           Launch Options                   ?" -ForegroundColor Cyan
Write-Host "??????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host "?  1. Run Full System (Main.java)           ?" -ForegroundColor Cyan
Write-Host "?  2. Run Unit Tests (EDSCTest.java)        ?" -ForegroundColor Cyan
Write-Host "?  3. Exit                                  ?" -ForegroundColor Cyan
Write-Host "??????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host ""

$choice = Read-Host "Select option (1-3)"

Write-Host ""

# Step 4: Execute selected option
Write-Host "[4/4] Launching application..." -ForegroundColor Yellow
Write-Host ""

switch ($choice) {
    "1" {
        Write-Host "Starting EDSC Full System..." -ForegroundColor Green
        Write-Host "????????????????????????????????????????????????" -ForegroundColor Green
        Write-Host ""
        java -cp out/production/blockchainProjekt com.company.Main
    }
    "2" {
        Write-Host "Running Unit Tests..." -ForegroundColor Green
        Write-Host "????????????????????????????????????????????????" -ForegroundColor Green
        Write-Host ""
        java -cp out/production/blockchainProjekt com.company.EDSCTest
    }
    "3" {
        Write-Host "Exiting..." -ForegroundColor Yellow
        exit 0
    }
    default {
        Write-Host "? Invalid option. Please select 1, 2, or 3." -ForegroundColor Red
        exit 1
    }
}

Write-Host ""
Write-Host "? Program completed successfully!" -ForegroundColor Green
